def seed_disease_scans(db: Session) -> None:
    """Insert initial disease scans if table is missing geo-referenced peer scans. Idempotent."""
    geo_count = db.query(DiseaseScan).filter(DiseaseScan.lat.isnot(None), DiseaseScan.lon.isnot(None)).count()
    if geo_count >= len(SEED_DISEASE_SCANS):
        return

    now = datetime.utcnow()
    for item in SEED_DISEASE_SCANS:
        data = dict(item)
        offset = data.pop("created_at_offset", timedelta())
        scan = DiseaseScan(
            id=uuid.uuid4(),
            created_at=now - offset,
            **data,
        )
        db.add(scan)

    db.commit()
    print(f"[seed] Seeded {len(SEED_DISEASE_SCANS)} verified peer disease scans into database.")


def run_all_seeds() -> None:
    """Entry-point called from FastAPI on_startup."""
    db = SessionLocal()
    try:
        seed_operators(db)
        seed_disease_scans(db)
    except Exception as exc:
        print(f"[seed] ⚠️  Seed failed (non-fatal): {exc}")
        db.rollback()
    finally:
        db.close()
