def seed_operators(db: Session) -> None:
    """Insert operators if the table is empty. Idempotent."""
    count = db.query(Operator).count()
    if count > 0:
        print(f"[seed] operators table already has {count} rows — skipping.")
        return

    now = datetime.utcnow()
    for data in SEED_OPERATORS:
        op = Operator(
            id=uuid.uuid4(),
            created_at=now,
            **data,
        )
        db.add(op)

    db.commit()
    print(f"[seed] ✅ Seeded {len(SEED_OPERATORS)} operators into the database.")


